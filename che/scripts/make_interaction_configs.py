"""Emit the interaction check's three new θ* conditions (POST HOC, eval-only).

Authorized by the decision log's PAPER V3 item 2(a); scope θ* only (PAPER V3
PHASE 1 START item 2). Plan:
`che/bench/results/phase6/post_v3_interaction/PLAN.md` §2.

The four conditions are θ* with κ_A and κ_B switched off or left on:

    neither   κ_A = 0     κ_B = 0
    a_only    κ_A = θ*'s  κ_B = 0
    b_only    κ_A = 0     κ_B = θ*'s
    both      θ* itself (`theta_star_holdout.yaml`; no new file)

Each new file is θ*'s file with a new header and ONLY its κ lines rewritten,
so the diff against θ* is the header plus at most two lines. The values come
from θ*'s own file, never from a constant typed here, and
`test_interaction_check.py` re-derives every file and compares it byte for
byte. Existing configs are never edited.

Usage:
    uv run python -m che.scripts.make_interaction_configs           # write
    uv run python -m che.scripts.make_interaction_configs --check   # compare
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
THETA_STAR = "che/configs/theta_star_holdout.yaml"

# condition -> (Coupling A on?, Coupling B on?)
CONDITIONS = {
    "neither": (False, False),
    "a_only": (True, False),
    "b_only": (False, True),
    "both": (True, True),
}
NEW_CONDITIONS = ("neither", "a_only", "b_only")


def config_path(cond: str) -> str:
    """Repo-relative config for a condition; 'both' is θ*'s own file."""
    if cond not in CONDITIONS:
        raise ValueError(f"unknown condition {cond!r}")
    if cond == "both":
        return THETA_STAR
    return f"che/configs/interaction_{cond}.yaml"


_KAPPA = re.compile(r"^(  kappa_(A|B): )(\S+)(.*)$")


def _header(cond: str) -> str:
    a_on, b_on = CONDITIONS[cond]
    on = {True: "theta*'s value", False: "0 (OFF)"}
    return (
        f"# INTERACTION CHECK, condition '{cond}': theta* with kappa_A = "
        f"{on[a_on]}, kappa_B = {on[b_on]}.\n"
        "#\n"
        "# POST HOC, EVAL-ONLY. Authorized by docs/decision_log.md, PAPER V3\n"
        "# item 2(a); scope theta* only (PAPER V3 PHASE 1 START item 2). Plan:\n"
        "# che/bench/results/phase6/post_v3_interaction/PLAN.md. NEVER a\n"
        "# training config, and not part of the registered Phase-6 design.\n"
        "#\n"
        f"# GENERATED by che/scripts/make_interaction_configs.py from\n"
        f"# {THETA_STAR}: its body verbatim, only the kappa line(s) below\n"
        "# rewritten. With kappa = 0 the env is the nested model, bitwise\n"
        "# (CLAUDE.md invariant 3). Do not hand-edit; regenerate.\n"
    )


def render(cond: str, theta_star_text: str) -> str:
    """θ*'s text with a new header and the condition's κ lines rewritten."""
    if cond not in NEW_CONDITIONS:
        raise ValueError(f"{cond!r} has no generated file")
    a_on, b_on = CONDITIONS[cond]
    keep = {"A": a_on, "B": b_on}
    lines = theta_star_text.splitlines()
    body_start = next(i for i, ln in enumerate(lines) if ln.startswith("env:"))
    out, seen = [], set()
    for ln in lines[body_start:]:
        m = _KAPPA.match(ln)
        if m:
            which = m.group(2)
            seen.add(which)
            if not keep[which]:
                ln = (
                    f"{m.group(1)}0.0  # INTERACTION CHECK: OFF "
                    f"(theta* value {m.group(3)})"
                )
        out.append(ln)
    if seen != {"A", "B"}:
        raise ValueError(f"{THETA_STAR}: kappa lines not found as expected ({seen})")
    return _header(cond) + "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    a = ap.parse_args(argv)
    src = (REPO_ROOT / THETA_STAR).read_text()
    bad = []
    for cond in NEW_CONDITIONS:
        path = REPO_ROOT / config_path(cond)
        want = render(cond, src)
        if a.check:
            if not path.is_file() or path.read_text() != want:
                bad.append(str(path))
        else:
            path.write_text(want)
            print(f"wrote {config_path(cond)}")
    if bad:
        print("STALE or missing: " + ", ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
