"""Emit the interaction check's new conditions (POST HOC, eval-only).

Authorized by the decision log's PAPER V3 item 2(a) (θ*; PAPER V3 PHASE 1
START item 2); the links-open condition by PLAN AMENDMENT item 4 (2026-10-17);
the High-severity 2×2 by GO/NO-GO PROBE (2026-11-10). Plan:
`che/bench/results/phase6/post_v3_interaction/PLAN.md` §2.

The 2×2 interaction conditions are θ* with κ_A and κ_B switched off or left
on, and the fifth is θ* with the links open:

    neither     κ_A = 0     κ_B = 0     δ = θ*'s
    a_only      κ_A = θ*'s  κ_B = 0     δ = θ*'s
    b_only      κ_A = 0     κ_B = θ*'s  δ = θ*'s
    both        θ* itself (`theta_star_holdout.yaml`; no new file)
    links_open  κ_A = θ*'s  κ_B = θ*'s  δ = 0

The High-severity 2×2 is the same switch-off applied to the all-on High
config (`joint_high.yaml`, which is θ* with β = 0.70):

    high_neither  κ_A = 0       κ_B = 0       β = 0.70
    high_a_only   κ_A = High's  κ_B = 0       β = 0.70
    high_b_only   κ_A = 0       κ_B = High's  β = 0.70
    high_both     `joint_high.yaml` itself (no new file)

Each new file is its base file (θ*'s, or the all-on High config) with a new
header and ONLY its κ or δ lines rewritten, so the diff against the base is the
header plus at most two lines. The values come from the base file, never from
a constant typed here, and `test_interaction_check.py` re-derives every file
and compares it byte for byte. Existing configs are never edited.

Usage:
    uv run python -m che.scripts.make_interaction_configs           # write
    uv run python -m che.scripts.make_interaction_configs --check   # compare
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
THETA_STAR = "che/configs/theta_star_holdout.yaml"
# The all-on High config: θ* with β = 0.70 (the base of the High 2×2).
HIGH = "che/configs/joint_high.yaml"

# The 2×2 of the interaction contrast: condition -> (Coupling A on?, B on?)
CONDITIONS = {
    "neither": (False, False),
    "a_only": (True, False),
    "b_only": (False, True),
    "both": (True, True),
}
# The fifth condition: θ* with the links open (δ = 0), both couplings on.
LINKS_OPEN = "links_open"
# The θ* block: the 2×2 plus links_open (PLAN §2).
THETA_STAR_CONDITIONS = (*CONDITIONS, LINKS_OPEN)
# The High block: the same 2×2 on the all-on High config (GO/NO-GO PROBE).
HIGH_CONDITIONS = {f"high_{c}": on for c, on in CONDITIONS.items()}
ALL_CONDITIONS = (*THETA_STAR_CONDITIONS, *HIGH_CONDITIONS)
NEW_CONDITIONS = (
    "neither",
    "a_only",
    "b_only",
    LINKS_OPEN,
    "high_neither",
    "high_a_only",
    "high_b_only",
)


def base_path(cond: str) -> str:
    """The existing config a condition is derived from."""
    if cond not in ALL_CONDITIONS:
        raise ValueError(f"unknown condition {cond!r}")
    return HIGH if cond in HIGH_CONDITIONS else THETA_STAR


def config_path(cond: str) -> str:
    """Repo-relative config for a condition.

    'both' is θ*'s own file and 'high_both' is the all-on High config's.
    """
    base = base_path(cond)
    if cond in ("both", "high_both"):
        return base
    return f"che/configs/interaction_{cond}.yaml"


_KAPPA = re.compile(r"^(  kappa_(A|B): )(\S+)(.*)$")
_DELTA = re.compile(r"^(  delta: )(\S+)(.*)$")


def _header_high(cond: str) -> str:
    on = {True: "High's value", False: "0 (OFF)"}
    a_on, b_on = HIGH_CONDITIONS[cond]
    return (
        f"# INTERACTION CHECK, condition '{cond}': the all-on High config\n"
        f"# (beta = 0.70) with kappa_A = {on[a_on]}, kappa_B = {on[b_on]}.\n"
        "#\n"
        "# POST HOC, EVAL-ONLY. Authorized by docs/decision_log.md, GO/NO-GO\n"
        "# PROBE (2026-11-10): the High-severity 2x2. Plan:\n"
        "# che/bench/results/phase6/post_v3_interaction/PLAN.md. NEVER a\n"
        "# training config, and not part of the registered Phase-6 design.\n"
        "#\n"
        f"# GENERATED by che/scripts/make_interaction_configs.py from\n"
        f"# {HIGH}: its body verbatim, only the kappa line(s) below\n"
        "# rewritten. With kappa = 0 the env is the nested model, bitwise\n"
        "# (CLAUDE.md invariant 3). Do not hand-edit; regenerate.\n"
    )


def _header(cond: str) -> str:
    if cond in HIGH_CONDITIONS:
        return _header_high(cond)
    on = {True: "theta*'s value", False: "0 (OFF)"}
    if cond == LINKS_OPEN:
        what = (
            "theta* with delta = 0 (links OPEN), kappa_A and kappa_B at "
            "theta*'s values."
        )
        auth = (
            "# POST HOC, EVAL-ONLY. Authorized by docs/decision_log.md,\n"
            "# PLAN AMENDMENT item 4 (2026-10-17); scope theta* only. Plan:\n"
        )
        knob = ("the delta line", "delta")
    else:
        a_on, b_on = CONDITIONS[cond]
        what = f"theta* with kappa_A = {on[a_on]}, kappa_B = {on[b_on]}."
        auth = (
            "# POST HOC, EVAL-ONLY. Authorized by docs/decision_log.md, PAPER V3\n"
            "# item 2(a); scope theta* only (PAPER V3 PHASE 1 START item 2). Plan:\n"
        )
        knob = ("the kappa line(s)", "kappa")
    return (
        f"# INTERACTION CHECK, condition '{cond}': {what}\n"
        "#\n"
        f"{auth}"
        "# che/bench/results/phase6/post_v3_interaction/PLAN.md. NEVER a\n"
        "# training config, and not part of the registered Phase-6 design.\n"
        "#\n"
        f"# GENERATED by che/scripts/make_interaction_configs.py from\n"
        f"# {THETA_STAR}: its body verbatim, only {knob[0]} below\n"
        f"# rewritten. With {knob[1]} = 0 the env is the nested model, bitwise\n"
        "# (CLAUDE.md invariant 3). Do not hand-edit; regenerate.\n"
    )


def render(cond: str, base_text: str) -> str:
    """The base's text with a new header and the condition's κ or δ lines rewritten.

    `base_text` is the text of `base_path(cond)`: θ*'s file, or the all-on High
    config for a High condition.
    """
    if cond not in NEW_CONDITIONS:
        raise ValueError(f"{cond!r} has no generated file")
    base = base_path(cond)
    was = "High's value" if cond in HIGH_CONDITIONS else "theta* value"
    if cond == LINKS_OPEN:
        keep = {"A": True, "B": True}
    else:
        a_on, b_on = {**CONDITIONS, **HIGH_CONDITIONS}[cond]
        keep = {"A": a_on, "B": b_on}
    lines = base_text.splitlines()
    body_start = next(i for i, ln in enumerate(lines) if ln.startswith("env:"))
    out, seen, n_delta = [], set(), 0
    for ln in lines[body_start:]:
        m = _KAPPA.match(ln)
        d = _DELTA.match(ln)
        if m:
            which = m.group(2)
            seen.add(which)
            if not keep[which]:
                ln = f"{m.group(1)}0.0  # INTERACTION CHECK: OFF ({was} {m.group(3)})"
        elif d:
            n_delta += 1
            if cond == LINKS_OPEN:
                ln = (
                    f"{d.group(1)}0.0  # INTERACTION CHECK: links OPEN "
                    f"(theta* value {d.group(2)})"
                )
        out.append(ln)
    if seen != {"A", "B"} or n_delta != 1:
        raise ValueError(
            f"{base}: kappa/delta lines not found as expected "
            f"({seen}, {n_delta} delta lines)"
        )
    return _header(cond) + "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    a = ap.parse_args(argv)
    bad = []
    for cond in NEW_CONDITIONS:
        path = REPO_ROOT / config_path(cond)
        want = render(cond, (REPO_ROOT / base_path(cond)).read_text())
        if a.check:
            if not path.is_file() or path.read_text() != want:
                bad.append(str(path))
        else:
            path.write_text(want)
            print(f"wrote {config_path(cond)}")
    if bad:
        print("STALE or missing: " + ", ".join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
